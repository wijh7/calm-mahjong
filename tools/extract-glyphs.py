# Build-time only: turns font glyphs into vector paths so the game NEVER depends on a runtime font
# for tile faces (the classic "[][][]" tofu bug). Noto CJK is SIL OFL licensed.
import sys, json
from fontTools.ttLib import TTCollection
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.pens.boundsPen import BoundsPen
src, out = sys.argv[1], sys.argv[2]
coll = TTCollection(src)
font = next(f for f in coll.fonts if 'JP' in f['name'].getDebugName(1))
cmap = font.getBestCmap(); gs = font.getGlyphSet()
chars = "一二三四五六七八九萬東南西北中發春夏秋冬梅蘭菊竹"
res = {}
for ch in chars:
    g = gs[cmap[ord(ch)]]
    bp = BoundsPen(gs); g.draw(bp); x0,y0,x1,y1 = bp.bounds
    pen = SVGPathPen(gs, ntos=lambda v: ('%.1f' % v).rstrip('0').rstrip('.'))
    tp = TransformPen(pen, (1,0,0,-1,-x0,y1))  # flip Y, origin at top-left of ink box
    g.draw(tp)
    res[ch] = {"d": pen.getCommands(), "w": round(x1-x0,1), "h": round(y1-y0,1)}
js = "// AUTO-GENERATED by tools/extract-glyphs.py (Noto Serif CJK JP Bold, SIL OFL)\nexport const GLYPHS = " + json.dumps(res, ensure_ascii=False, separators=(',',':')) + ";\n"
open(out,'w').write(js); print(len(js), "bytes", len(res), "glyphs")
